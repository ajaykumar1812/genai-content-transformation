import os
import re
from io import BytesIO
from xml.sax.saxutils import escape
from docx import Document
from docx.shared import Pt, Inches, RGBColor

def export_as_txt(content: str, title: str = "Transformed Content"):
    """Returns a BytesIO stream containing UTF-8 encoded text."""
    buffer = BytesIO()
    header = f"=== {title} ===\n" + ("=" * (len(title) + 8)) + "\n\n"
    full_text = header + content
    buffer.write(full_text.encode("utf-8"))
    buffer.seek(0)
    filename = re.sub(r'[^a-zA-Z0-9_\-]', '_', title.lower())[:40] + ".txt"
    return buffer, "text/plain", filename

def export_as_docx(title: str, content: str):
    """Generates a styled Microsoft Word document (.docx)."""
    doc = Document()
    
    # Document Title
    heading = doc.add_heading(title or "Gen AI Content Transformation", level=0)
    heading.paragraph_format.space_after = Pt(10)
    
    # Subtitle / Metadata
    p_meta = doc.add_paragraph()
    run_meta = p_meta.add_run("Generated by Gen AI Platform for Automated Content Transformation")
    run_meta.italic = True
    run_meta.font.size = Pt(9.5)
    run_meta.font.color.rgb = RGBColor(100, 116, 139)
    p_meta.paragraph_format.space_after = Pt(14)
    
    # Parse lines into structured Word elements
    for raw_line in content.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("# "):
            doc.add_heading(line.lstrip("# ").strip(), level=1)
        elif line.startswith("## "):
            doc.add_heading(line.lstrip("# ").strip(), level=2)
        elif line.startswith("### "):
            doc.add_heading(line.lstrip("# ").strip(), level=3)
        elif line.startswith(("- ", "* ", "• ")):
            clean_item = re.sub(r'^[-*•]\s*', '', line).strip()
            p = doc.add_paragraph(clean_item, style='List Bullet')
            p.paragraph_format.space_after = Pt(4)
        elif re.match(r'^\d+\.\s+', line):
            num_item = re.sub(r'^\d+\.\s+', '', line).strip()
            p = doc.add_paragraph(num_item, style='List Number')
            p.paragraph_format.space_after = Pt(4)
        else:
            p = doc.add_paragraph(line)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            
    buffer = BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    filename = re.sub(r'[^a-zA-Z0-9_\-]', '_', (title or "transformed_content").lower())[:40] + ".docx"
    return buffer, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", filename

def export_as_pdf(title: str, content: str):
    """Generates a styled PDF document using ReportLab."""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=A4,
            rightMargin=48, leftMargin=48,
            topMargin=48, bottomMargin=48
        )
        styles = getSampleStyleSheet()
        
        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Title'],
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0f172a'),
            spaceAfter=8
        )
        h1_style = ParagraphStyle(
            'CustomH1',
            parent=styles['Heading1'],
            fontSize=15,
            leading=19,
            textColor=colors.HexColor('#1e40af'),
            spaceBefore=12,
            spaceAfter=6
        )
        h2_style = ParagraphStyle(
            'CustomH2',
            parent=styles['Heading2'],
            fontSize=12.5,
            leading=16,
            textColor=colors.HexColor('#0f766e'),
            spaceBefore=10,
            spaceAfter=4
        )
        body_style = ParagraphStyle(
            'CustomBody',
            parent=styles['BodyText'],
            fontSize=10,
            leading=14.5,
            textColor=colors.HexColor('#334155'),
            spaceAfter=6
        )
        bullet_style = ParagraphStyle(
            'CustomBullet',
            parent=body_style,
            leftIndent=14,
            spaceAfter=3
        )
        
        story = [
            Paragraph(escape(title or "Gen AI Content Transformation"), title_style),
            Paragraph("<i>Automated deliverable generated by Gen AI Platform</i>", styles['Italic']),
            Spacer(1, 12)
        ]
        
        for raw_line in content.splitlines():
            line = raw_line.strip()
            if not line:
                continue
            if line.startswith("# "):
                story.append(Paragraph(escape(line.lstrip("# ").strip()), h1_style))
            elif line.startswith("## ") or line.startswith("### "):
                story.append(Paragraph(escape(line.lstrip("# ").strip()), h2_style))
            elif line.startswith(("- ", "* ", "• ")):
                clean_bullet = "&#8226; " + escape(re.sub(r'^[-*•]\s*', '', line).strip())
                story.append(Paragraph(clean_bullet, bullet_style))
            elif re.match(r'^\d+\.\s+', line):
                clean_num = escape(line)
                story.append(Paragraph(clean_num, bullet_style))
            else:
                story.append(Paragraph(escape(line), body_style))
                
        doc.build(story)
        buffer.seek(0)
        filename = re.sub(r'[^a-zA-Z0-9_\-]', '_', (title or "transformed_content").lower())[:40] + ".pdf"
        return buffer, "application/pdf", filename
    except ImportError:
        return export_as_txt(f"=== {title} ===\n\n{content}", title=title)

def export_as_pptx(title: str, content: str):
    """Generates PowerPoint presentation slides (.pptx) using python-pptx."""
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
        from pptx.dml.color import RGBColor
        
        prs = Presentation()
        # Title Slide
        title_slide = prs.slides.add_slide(prs.slide_layouts[0])
        title_slide.shapes.title.text = title or "Gen AI Presentation"
        subtitle = title_slide.placeholders[1]
        subtitle.text = "Generated by Gen AI Platform for Automated Content Transformation"
        
        current_title = None
        bullets = []
        
        def commit_slide(slide_title, items):
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            slide.shapes.title.text = (slide_title or "Key Insights")[:90]
            tf = slide.placeholders[1].text_frame
            tf.clear()
            for idx, item in enumerate(items[:6]):
                p = tf.paragraphs[0] if idx == 0 else tf.add_paragraph()
                p.text = item[:250]
                p.level = 0
                p.font.size = Pt(17)
                
        for raw in content.splitlines():
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#") or (len(line) < 80 and line.endswith(":")):
                if current_title and bullets:
                    commit_slide(current_title, bullets)
                current_title = line.lstrip("#").strip().rstrip(":")
                bullets = []
            elif line.startswith(("-", "*", "•")):
                bullets.append(re.sub(r'^[-*•]\s*', '', line).strip())
            elif current_title:
                bullets.append(line)
                
        if current_title and bullets:
            commit_slide(current_title, bullets)
            
        if len(prs.slides) == 1:
            paragraphs = [p.strip() for p in content.splitlines() if p.strip()]
            for chunk_start in range(0, min(len(paragraphs), 30), 5):
                commit_slide(f"Key Points {chunk_start // 5 + 1}", paragraphs[chunk_start:chunk_start+5])
                
        buffer = BytesIO()
        prs.save(buffer)
        buffer.seek(0)
        filename = re.sub(r'[^a-zA-Z0-9_\-]', '_', (title or "presentation").lower())[:40] + ".pptx"
        return buffer, "application/vnd.openxmlformats-officedocument.presentationml.presentation", filename
    except ImportError:
        return export_as_txt(f"=== PRESENTATION: {title} ===\n\n{content}", title=title)
