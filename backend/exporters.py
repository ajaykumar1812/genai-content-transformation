import os
from io import BytesIO
from xml.sax.saxutils import escape
from docx import Document
from docx.shared import Pt, Inches, RGBColor

def export_as_txt(content):
    """Returns a BytesIO stream containing UTF-8 encoded text."""
    buffer = BytesIO()
    buffer.write(content.encode("utf-8"))
    buffer.seek(0)
    return buffer, "text/plain", "transformed_content.txt"

def export_as_docx(title, content):
    """Generates a styled Microsoft Word document (.docx)."""
    doc = Document()
    
    # Title
    heading = doc.add_heading(title or "Gen AI Content Transformation", level=0)
    heading.paragraph_format.space_after = Pt(12)
    
    # Metadata line
    p_meta = doc.add_paragraph()
    run_meta = p_meta.add_run("Generated with Gen AI Platform for Automated Content Transformation")
    run_meta.italic = True
    run_meta.font.size = Pt(9)
    run_meta.font.color.rgb = RGBColor(128, 128, 128)
    doc.add_paragraph().paragraph_format.space_after = Pt(8)
    
    # Content paragraphs
    for raw_line in content.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("# "):
            doc.add_heading(line.lstrip("# ").strip(), level=1)
        elif line.startswith("## "):
            doc.add_heading(line.lstrip("# ").strip(), level=2)
        elif line.startswith("### "):
            doc.add_heading(line.lstrip("# ").strip(), level=3)
        elif line.startswith(("- ", "* ", "• ")):
            clean_item = line.lstrip("-*• ").strip()
            p = doc.add_paragraph(clean_item, style='List Bullet')
            p.paragraph_format.space_after = Pt(4)
        elif line.startswith(("1. ", "2. ", "3. ", "4. ", "5. ", "6. ", "7. ", "8. ", "9. ")):
            num_item = line.split(". ", 1)[-1]
            p = doc.add_paragraph(num_item, style='List Number')
            p.paragraph_format.space_after = Pt(4)
        else:
            p = doc.add_paragraph(line)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            
    buffer = BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "transformed_content.docx"

def export_as_pdf(title, content):
    """Generates a styled PDF document using ReportLab if available, or fallback."""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=A4,
            rightMargin=48, leftMargin=48,
            topMargin=48, bottomMargin=48
        )
        styles = getSampleStyleSheet()
        
        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Title'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#1e293b'),
            spaceAfter=12
        )
        h2_style = ParagraphStyle(
            'CustomH2',
            parent=styles['Heading2'],
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#0f766e'),
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'CustomBody',
            parent=styles['BodyText'],
            fontSize=10.5,
            leading=15,
            textColor=colors.HexColor('#334155'),
            spaceAfter=8
        )
        bullet_style = ParagraphStyle(
            'CustomBullet',
            parent=body_style,
            leftIndent=15,
            spaceAfter=4
        )
        
        story = [
            Paragraph(escape(title or "Gen AI Content Transformation"), title_style),
            Paragraph("<i>Automated deliverable generated by Gen AI Platform</i>", styles['Italic']),
            Spacer(1, 14)
        ]
        
        for raw_line in content.splitlines():
            line = raw_line.strip()
            if not line:
                continue
            if line.startswith("#"):
                story.append(Paragraph(escape(line.lstrip("# ").strip()), h2_style))
            elif line.startswith(("-", "*", "•")):
                clean_bullet = "&#8226; " + escape(line.lstrip("-*• ").strip())
                story.append(Paragraph(clean_bullet, bullet_style))
            else:
                story.append(Paragraph(escape(line), body_style))
                
        doc.build(story)
        buffer.seek(0)
        return buffer, "application/pdf", "transformed_content.pdf"
    except ImportError:
        # Fallback to plain text buffer with PDF mime or plain text
        return export_as_txt(f"=== {title} ===\n\n{content}")

def export_as_pptx(title, content):
    """Generates PowerPoint presentation slides (.pptx) using python-pptx."""
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
        from pptx.dml.color import RGBColor
        
        prs = Presentation()
        # Title Slide
        title_slide = prs.slides.add_slide(prs.slide_layouts[0])
        title_slide.shapes.title.text = title or "Gen AI Presentation"
        subtitle = title_slide.placeholders[1]
        subtitle.text = "Generated by Gen AI Platform for Automated Content Transformation"
        
        current_title = None
        bullets = []
        
        def commit_slide(slide_title, items):
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            slide.shapes.title.text = (slide_title or "Key Insights")[:90]
            tf = slide.placeholders[1].text_frame
            tf.clear()
            for idx, item in enumerate(items[:6]):
                p = tf.paragraphs[0] if idx == 0 else tf.add_paragraph()
                p.text = item[:250]
                p.level = 0
                p.font.size = Pt(18)
                
        for raw in content.splitlines():
            line = raw.strip()
            if not line:
                continue
            if line.startswith("#") or (len(line) < 80 and line.endswith(":")):
                if current_title and bullets:
                    commit_slide(current_title, bullets)
                current_title = line.lstrip("#").strip().rstrip(":")
                bullets = []
            elif line.startswith(("-", "*", "•")):
                bullets.append(line.lstrip("-*• ").strip())
            elif current_title:
                bullets.append(line)
                
        if current_title and bullets:
            commit_slide(current_title, bullets)
            
        if len(prs.slides) == 1:
            # Fallback if no specific headers were detected
            paragraphs = [p.strip() for p in content.splitlines() if p.strip()]
            for chunk_start in range(0, min(len(paragraphs), 30), 5):
                commit_slide(f"Key Points {chunk_start // 5 + 1}", paragraphs[chunk_start:chunk_start+5])
                
        buffer = BytesIO()
        prs.save(buffer)
        buffer.seek(0)
        return buffer, "application/vnd.openxmlformats-officedocument.presentationml.presentation", "transformed_presentation.pptx"
    except ImportError:
        return export_as_txt(f"=== PRESENTATION: {title} ===\n\n{content}")
